import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:5311/chapters/04/');
  await page.locator('[data-action="start"]:not([disabled])').click();
  await page.getByRole('button', { name: '课程', exact: true }).click();
  await page.locator('.journey .panel-pages button').nth(1).click();
  await page.locator('[data-action="activity-06"]:visible').click();
  if (await page.locator('[data-action="tab-steps"]:visible').count()) await page.locator('[data-action="tab-steps"]:visible').click();
  await page.locator('[data-action="screen-add"]').click();
  await page.locator('[data-action="add-take"]').click();
  const row = page.locator('.action-list > li:visible');
  const added = await row.getAttribute('data-card-id');
  await row.locator('.stepper-button').last().click();
  await page.waitForTimeout(300);
  assert.equal(await row.getAttribute('data-card-id'), added);
  assert.match(await row.locator('.stepper-value').innerText(), /2/);
  await row.locator('[data-action^="move-up-"]').click();
  await page.waitForTimeout(300);
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('nova-action-workshop-v1')).workspaces['course:06'].plan);
  const changed = await read();
  assert.equal(changed.find(card => card.id === added).amount, 2);
  const pager = page.locator('.action-list + .record-pages select');
  await pager.selectOption('order:0');
  assert.ok(await page.locator('.order-overview > li:visible').count() > 1);
  const cards = page.locator('.order-overview > li:visible');
  const moved = await cards.first().getAttribute('data-card-id');
  const grip = await cards.first().locator('.action-grip').boundingBox();
  const target = await cards.nth(2).boundingBox();
  await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2);
  await page.mouse.down(); await page.mouse.move(target.x + 70, target.y + target.height - 4, { steps: 10 }); await page.mouse.up();
  await page.waitForTimeout(300);
  const reordered = await read();
  assert.notEqual(reordered.findIndex(card => card.id === moved), 0);
  assert.equal(reordered.length, changed.length);
  assert.deepEqual(errors, []);
  await page.screenshot({ path: 'tmp/single-screen/paged-plan-1366.png' });
  await fs.writeFile('tmp/single-screen/paged-plan.json', JSON.stringify({ addedEditedAndMoved: true, dragReordered: true, preservedCount: reordered.length, errors }, null, 2));
  console.log('PASS: add, edit, move across pages and drag ordering');
} finally { await browser.close(); }
