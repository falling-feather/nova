为什么每次只调“一点点”？研究者常用下山来打比方。想象你站在一座大雾弥漫的山上，看不清山脚在哪里，只能用脚感受地面往哪边倾斜。最稳妥的办法，是朝着最陡的下坡方向迈一小步，再感受一次，再迈一小步。误差就像山的高度，反向传播告诉每个旋钮“下坡”在哪个方向，一小步一小步，网络的误差就越来越低。步子迈得太大，反而可能一脚跨到对面的山坡上去。

