一块方糖、一滴香水、一粒药片，看上去各不相同，往小里看，都是由原子连成的分子。化学家常常要回答一个问题：手里这种物质的分子，原子究竟是怎样连在一起的？同样几种原子，连法不同，就可能是完全不同的物质，有的香甜，有的有毒。

