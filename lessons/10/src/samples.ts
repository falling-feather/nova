import type { PixelImage, TrainingSample } from './model.ts';

export const CLASS_IDS = ['pencil', 'cup', 'book'] as const;
export type ClassId = typeof CLASS_IDS[number];
export const CLASS_NAMES: Record<ClassId, string> = { pencil: '文具 · 铅笔', cup: '水杯', book: '书本' };
export const CLASS_SHORT: Record<ClassId, string> = { pencil: '铅笔', cup: '水杯', book: '书本' };
export type Scene = 'studio' | 'mixed' | 'dim';
export interface CaptureGroup { id: string; seed: number; scene: Scene; name: string; source: 'synthetic-v1'; }
export const SCENE_NAMES: Record<Scene, string> = { studio: '彩色展台', mixed: '交换物件颜色', dim: '暖光木桌' };

export function makeGroup(id: string, seed: number, scene: Scene): CaptureGroup {
  return { id, seed, scene, name: `${id} · ${SCENE_NAMES[scene]}`, source: 'synthetic-v1' };
}

function random(seed: number): () => number {
  let state = seed >>> 0;
  return () => { state = (Math.imul(state, 1664525) + 1013904223) >>> 0; return state / 4294967296; };
}

export function sampleId(group: CaptureGroup, index: number): string { return `${group.id}-${CLASS_IDS[Math.floor(index / 2)]}-${index % 2 + 1}`; }
export function referenceLabel(index: number): ClassId { return CLASS_IDS[Math.floor(index / 2)]; }

/** Pixels are generated by the same deterministic raster recipe used for display and learning. */
export function sampleImage(group: CaptureGroup, index: number): PixelImage {
  if (!Number.isInteger(index) || index < 0 || index >= 6) throw new Error('样本编号必须在0至5之间。');
  const rng = random(group.seed * 31 + index * 701);
  const classIndex = Math.floor(index / 2);
  const angle = (rng() - 0.5) * 0.3 + (classIndex === 0 ? -0.19 : 0);
  const scale = 0.88 + rng() * 0.18;
  const shiftX = (rng() - 0.5) * 4, shiftY = (rng() - 0.5) * 4;
  const stretch = 0.91 + random(group.seed + classIndex * 97)() * 0.18;
  const colors = [[183, 80, 32], [26, 113, 123], [111, 70, 155]];
  const colorIndex = group.scene === 'studio' ? classIndex : (classIndex + 1 + group.seed % 2) % 3;
  const color = colors[colorIndex];
  const background = group.scene === 'dim' ? [238, 224, 195] : [239, 240, 229];
  const light = group.scene === 'dim' ? 0.77 : 0.88 + rng() * 0.16;
  const data = new Uint8ClampedArray(64 * 64 * 4);
  const cosine = Math.cos(angle), sine = Math.sin(angle);
  for (let py = 0; py < 64; py++) for (let px = 0; px < 64; px++) {
    const dx = (px - 31.5 - shiftX) / scale, dy = (py - 31.5 - shiftY) / scale;
    const x = (dx * cosine + dy * sine) / stretch, y = -dx * sine + dy * cosine;
    let inside = false, detail = false;
    if (classIndex === 0) {
      inside = (Math.abs(x) < 4.8 && y > -22 && y < 17) || (y >= 17 && y < 25 && Math.abs(x) < (25 - y) * 0.6);
      detail = y < -17 || (y > 22) || (Math.abs(x - 1.3) < 0.65 && y < 17);
    } else if (classIndex === 1) {
      const body = x > -13 && x < 10 && y > -13 && y < 18 && ((Math.abs(x + 1.5) < 9.5) || y < 14);
      const ring = ((x - 13) / 9) ** 2 + ((y - 1) / 11) ** 2;
      const handle = ring < 1 && ring > 0.43 && x > 9;
      inside = body || handle;
      detail = body && y < -9;
    } else {
      inside = Math.abs(x) < 19 && Math.abs(y) < 15;
      detail = Math.abs(x + 11.5) < 1.2 || (y > 9 && x > -8) || (Math.abs(y + 5) < 1 && x > -6 && x < 12);
    }
    const offset = (py * 64 + px) * 4;
    for (let channel = 0; channel < 3; channel++) {
      const grain = (random(group.seed + px * 41 + py * 1009)() - 0.5) * 4;
      data[offset + channel] = inside ? color[channel] * light * (detail ? 0.65 : 0.94 + (px / 64) * 0.09) : background[channel] + grain;
    }
    data[offset + 3] = 255;
  }
  return { width: 64, height: 64, data };
}

export function samplesForGroups(groups: CaptureGroup[], labels: Record<string, ClassId> = {}): TrainingSample[] {
  return groups.flatMap(group => Array.from({ length: 6 }, (_, i) => ({
    id: sampleId(group, i), groupId: group.id, label: labels[sampleId(group, i)] ?? referenceLabel(i), image: sampleImage(group, i),
  })));
}

export function unknownImage(): PixelImage {
  const image = sampleImage(makeGroup('unknown', 404, 'studio'), 0);
  const data = new Uint8ClampedArray(image.data);
  for (let y = 0; y < 64; y++) for (let x = 0; x < 64; x++) {
    const p = (y * 64 + x) * 4;
    const inToy = y > 12 && y < 51 && Math.abs(x - 32) < (y - 12) * 0.6;
    data[p] = inToy ? 183 : 239;
    data[p + 1] = inToy ? 80 : 240;
    data[p + 2] = inToy ? 32 : 229;
  }
  return { width: 64, height: 64, data };
}
